-- SINGLE-PASSWORD MODE NOTICE
--
-- This deployment intentionally uses a client-side password gate only.
-- Do not run the previous admin_users RLS policy with this frontend: without a
-- Supabase Auth session, the admin UI would be unable to read or update tickets.
--
-- A static GitHub Pages site cannot prove to Supabase that the person who typed
-- the password is the administrator. Any anon policy that lets this frontend
-- update or delete tickets also lets someone call the same API outside the UI.
--
-- This file intentionally performs no database changes. To enforce permissions
-- at database level, migrate the frontend back to Supabase Auth and then apply
-- role-based Row Level Security policies.
